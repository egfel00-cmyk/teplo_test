// 146-а (власник 14.11: «перепровір, щоб превью картинок чітко на табло»): рамка превью — рядок із показаннями, а не найбільші цифри кадру.
// Лише синтетика: результат рушія {lines, drums, w, h} руками.
const V = require('../web/src/recognize.js');
let pass = 0, fail = 0;
const ok = (n, c, x) => { if (c) { pass++; console.log('  OK  ' + n); } else { fail++; console.log(' FAIL ' + n + (x !== undefined ? ' → ' + JSON.stringify(x) : '')); } };
const near = (a, b) => Math.abs(a - b) < 0.02;

// ЖК електролічильника в гаражі: великий напис «5(60) A» на корпусі, заводський номер, табло з 2263,4 кВт·год
const lcd = { w: 1000, h: 1400, drums: [], lines: [
  { text: '5(60)A 230V', score: 0.95, x: 100, y: 1100, w: 800, h: 120 },   // найвищий рядок із цифрами — наклейка
  { text: '№ 0122637', score: 0.93, x: 300, y: 1250, w: 400, h: 60 },       // заводський номер містить «2263»
  { text: '002263,4', score: 0.9, x: 280, y: 520, w: 440, h: 90 },          // табло
  { text: 'kWh', score: 0.9, x: 740, y: 540, w: 100, h: 50 } ] };
const f0 = V.focusOf(lcd);
ok('без показань — рядок, що майже самі цифри (табло), а не напис «5(60)A 230V»', f0 && near(f0.y, 565 / 1400), f0);
const f1 = V.focusOf(lcd, ['2263']);
ok('з показаннями 2263 — рядок табло, не наклейка й не заводський номер', f1 && near(f1.x, 500 / 1000) && near(f1.y, 565 / 1400) && near(f1.w, 0.44), f1);
ok('показання з дробом «2263,4» — те саме табло', (() => { const f = V.focusOf(lcd, ['2263,4']); return f && near(f.y, 565 / 1400); })());
ok('кілька зон (T1 2263, T2 811): рамка — рядок з однією з них', (() => { const f = V.focusOf(lcd, ['2263', '811']); return f && near(f.y, 565 / 1400); })());
ok('цифр показань на фото немає — як без показань', (() => { const f = V.focusOf(lcd, ['9999']); return f && near(f.y, f0.y); })());
// табло нечитке — лишились тільки написи з цифрами: беремо найкращий з них (як раніше), не центр фото
ok('лише написи з цифрами — найбільший напис', (() => { const f = V.focusOf({ w: 1000, h: 1400, drums: [], lines: lcd.lines.slice(0, 1) }); return f && near(f.y, 1160 / 1400); })());
ok('коротке число (< 3 цифр) не рахується', (() => { const f = V.focusOf(lcd, ['12']); return f && near(f.y, f0.y); })());

// барабан, знайдений за кольором (впевнено), — головніший за рядок тексту (там і червоні ролики)
const drum = { w: 1000, h: 1000, lines: [{ text: '00437', score: 0.9, x: 100, y: 100, w: 200, h: 50 }],
  drums: [{ text: '00437', sure: true, score: 1, x: 400, y: 450, w: 200, h: 60, angle: 0, rb: { x: 610, y: 450, w: 90, h: 60 } }] };
const f2 = V.focusOf(drum, ['437']);
ok('водомір: впевнене вікно барабана (з червоними) — не рядок тексту', f2 && near(f2.x, 0.55) && near(f2.y, 0.48), f2);

// водомір «Ванна» (скрин власника): вікно барабана не впевнене, на корпусі — номер «1640» і великий напис; збережено 919,403
const bath = { w: 1500, h: 2000, drums: [{ text: '00919', sure: false, score: 0.6, x: 600, y: 1200, w: 300, h: 80, angle: 0 }, { text: '1640', sure: false, score: 0.8, x: 100, y: 300, w: 200, h: 60, angle: 0 }],
  lines: [{ text: '1640', score: 0.95, x: 100, y: 300, w: 400, h: 150 }] };
const f3 = V.focusOf(bath, ['919,403']);
ok('вода: барабан з тими самими цифрами (919), не номер на корпусі', f3 && near(f3.x, 0.5) && near(f3.y, 1240 / 2000), f3);
// два вікна впевнено (два лічильники в кадрі) — рамка того, з якого зберегли
const two = { w: 1000, h: 1000, lines: [], drums: [{ text: '00437', sure: true, score: 1, x: 100, y: 100, w: 200, h: 60, angle: 0 }, { text: '00175', sure: true, score: 0.9, x: 600, y: 700, w: 200, h: 60, angle: 0 }] };
ok('два барабани: рамка по тому, де 175, а не навколо обох', (() => { const f = V.focusOf(two, ['175']); return f && near(f.x, 0.7) && near(f.y, 0.73) && f.w < 0.3; })());
ok('два барабани без показань — навколо обох (як раніше)', (() => { const f = V.focusOf(two); return f && f.w > 0.6; })());

// одне табло знайдено двічі (вужче й ширше, з сусідньою «m³») — без показань рамка не роздувається до обох
const dup = { w: 1200, h: 1600, lines: [], drums: [{ text: '00137', sure: true, score: 1, x: 410, y: 650, w: 400, h: 120, angle: 0 }, { text: '00137', sure: true, score: 0.9, x: 240, y: 640, w: 570, h: 150, angle: 0 }] };
ok('те саме табло двічі — найтісніша рамка', (() => { const f = V.focusOf(dup); return f && near(f.x, 610 / 1200) && near(f.w, 400 / 1200); })(), V.focusOf(dup));
// 147-а: тепло (ЖК) — рамка за збереженою енергією, після slim() (у файлі лишається лише це); заводський номер і модель — довші й «чисті» цифри
const heat = { w: 1200, h: 1600, drums: [], lines: [
  { text: '70751193', score: 0.97, x: 300, y: 1300, w: 600, h: 110, alts: ['70751198'] },   // заводський номер — більший за табло
  { text: 'SHARKY 774', score: 0.9, x: 350, y: 200, w: 500, h: 80 },
  { text: '15.482', score: 0.88, x: 380, y: 700, w: 420, h: 100 },                            // енергія на екрані
  { text: 'Gcal', score: 0.9, x: 820, y: 730, w: 120, h: 60 },
  { text: '12', score: 0.9, x: 100, y: 100, w: 40, h: 30 } ] };
const sl = V.slim(heat);
ok('slim: лише рядки з ≥ 3 цифрами, без alts; розмір кадру', sl && sl.w === 1200 && sl.lines.length === 3 && !sl.lines.some(l => l.alts) && sl.drums.length === 0, sl);
const h0 = V.focusOf(sl);
ok('тепло без показань — найбільші «чисті» цифри (заводський номер), як і раніше', h0 && near(h0.y, 1355 / 1600) && h0.v === 2, h0);
const h1 = V.focusOf(sl, ['15,482']);
ok('тепло: збережена енергія 15,482 — рамка на рядку екрана, v = 3', h1 && near(h1.y, 750 / 1600) && near(h1.x, 590 / 1200) && h1.v === 3, h1);
ok('тепло: енергія в ГДж на екрані (перераховано в Гкал) — шукаємо цифрами з екрана', (() => { const f = V.focusOf(sl, ['15.482']); return f && near(f.y, 750 / 1600); })());
console.log(`\nfocus.test: ${pass} ok, ${fail} fail`);
process.exit(fail ? 1 : 0);
