def load(p):
    d = json.load(open(p, encoding='utf-8')); return d, (d['admin_units'] if 'admin_units' in d else d[list(d.keys())[-1]])

def region(au, r, renamed, valid):
    lid, title = REGIONS[r]
    if r == 'ky':   # Київ — окремий рівень 1 (K), без районів-громад: один пункт
        h = {lid: {'n': 'Київ', 'd': lid}}
        s = [{'n': 'Київ', 'c': 'M', 'h': lid, 'd': lid, 'old': OLD['ky']['Київ']}]
        return {'r': r, 'oblast': title, 'src': 'КАТОТТГ (github.com/suprun/katottg.json), станом на ' + valid, 'districts': {lid: 'м. Київ'}, 'hromadas': h, 'settlements': s}
    xs = [x for x in au if x.get('level_1') == lid]
    P = {x['id']: x['name'] for x in xs if x['category'] == 'P'}
    H = {x['id']: {'n': x['name'], 'd': x['level_2']} for x in xs if x['category'] == 'H'}
    S = [{'n': x['name'], 'c': x['category'], 'h': x['level_3'], 'd': x['level_2'], 'id': x['id']} for x in xs if x['category'] in ('M', 'X', 'C')]
    hn = H_NEW.get(r, {})
    for h in H.values():
        if h['n'] in hn: h['old'] = [h['n']]; h['n'] = hn[h['n']]
    old, oldx = OLD.get(r, {}), OLD_X.get(r, {})
    # стара назва — місту з цією назвою, а якщо міста немає — селищу, далі селу (у Солоницівській громаді є селище Південне, яке Южним не було)
    tgt = {}
    for c in ('C', 'X', 'M'):
        for s in S:
            if s['c'] == c and s['n'] in old: tgt[s['n']] = c
    r24 = {}
    for e in R2024.get(r, []):
        hh = e[3] if len(e) > 3 else None
        cand = [s for s in S if s['n'] == e[0] and P.get(s['d']) == e[1] and (not hh or H.get(s['h'], {}).get('n', '').startswith(hh))]
        if len(cand) != 1: print('R2024', r, e, '→', len(cand), 'пунктів', [H.get(s['h'], {}).get('n') for s in cand], file=sys.stderr); continue
        r24.setdefault(cand[0]['id'], []).append(e[2])
    for s in S:
        al = (list(old.get(s['n'], [])) if tgt.get(s['n']) == s['c'] else []) + list(oldx.get(s['n'], [])) + ([renamed[s['id']]] if s['id'] in renamed else []) + r24.get(s['id'], [])
        al = [a for i, a in enumerate(al) if a and a != s['n'] and a not in al[:i]]
        if al: s['old'] = al
    # однакові назви громад в області (Чорноморська ×2 в Одеському районі, Калинівська, Лиманська): ключ довідника — «Назва (центр)»
    cnt = {}
    for h in H.values(): cnt[h['n']] = cnt.get(h['n'], 0) + 1
    for hid, h in H.items():
        if cnt[h['n']] > 1:
            ctr = next((s['n'] for s in S if s['h'] == hid), '')
            h['k'] = h['n'] + ' (' + ctr + ')'
    ks = [h.get('k') for h in H.values() if h.get('k')]
    for h in H.values():   # центри теж однакові (Калинівська ×2, обидві — Калинівка) — тоді район
        if h.get('k') and ks.count(h['k']) > 1: h['k'] = h['n'] + ' (' + P.get(h['d'], '') + ' р-н)'
    return {'r': r, 'oblast': title, 'src': 'КАТОТТГ (github.com/suprun/katottg.json), станом на ' + valid, 'districts': P, 'hromadas': H,
            'settlements': [{k: v for k, v in s.items() if k != 'id'} for s in S]}

